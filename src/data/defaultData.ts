export function computeTop20Consensus(managers: FPLManager[], players: FPLPlayer[]) {
  const playerMap = new Map<number, FPLPlayer>(players.map(p => [p.id, p]));
  
  // Ownership counts
  const ownershipMap = new Map<number, number>();
  const startingMap = new Map<number, number>();
  const captainMap = new Map<number, number>();
  const formationMap = new Map<string, number>();
  let totalValue = 0;
  let totalGwPoints = 0;
  let highestGw = { score: 0, manager: '', team: '' };

  managers.forEach(m => {
    totalValue += (m.value || 1000) / 10;
    totalGwPoints += m.event_total;
    if (m.event_total > highestGw.score) {
      highestGw = {
        score: m.event_total,
        manager: m.player_name,
        team: m.entry_name
      };
    }

    if (m.formation) {
      formationMap.set(m.formation, (formationMap.get(m.formation) || 0) + 1);
    }

    m.picks.forEach(p => {
      ownershipMap.set(p.element, (ownershipMap.get(p.element) || 0) + 1);
      if (p.position <= 11) {
        startingMap.set(p.element, (startingMap.get(p.element) || 0) + 1);
      }
      if (p.is_captain) {
        captainMap.set(p.element, (captainMap.get(p.element) || 0) + 1);
      }
    });
  });

  const topOwnedPlayers = Array.from(ownershipMap.entries())
    .map(([id, count]) => {
      const player = playerMap.get(id);
      return {
        player: player || ({ id, web_name: `Player #${id}`, element_type: 3, now_cost: 60, total_points: 100, team_short: 'PL' } as any),
        count,
        percent: Math.round((count / managers.length) * 100)
      };
    })
    .sort((a, b) => b.count - a.count);

  const captaincyDistribution = Array.from(captainMap.entries())
    .map(([id, count]) => {
      const player = playerMap.get(id);
      return {
        player: player || ({ id, web_name: `Player #${id}`, element_type: 3, now_cost: 60, total_points: 100, team_short: 'PL' } as any),
        count,
        percent: Math.round((count / managers.length) * 100)
      };
    })
    .sort((a, b) => b.count - a.count);

  const formationDistribution = Array.from(formationMap.entries())
    .map(([formation, count]) => ({
      formation,
      count,
      percent: Math.round((count / managers.length) * 100)
    }))
    .sort((a, b) => b.count - a.count);

  return {
    topOwnedPlayers,
    captaincyDistribution,
    formationDistribution,
    activeChipsCount: {},
    averageTeamValue: Number((totalValue / managers.length).toFixed(1)),
    averageGwPoints: Math.round(totalGwPoints / managers.length),
    highestGwScore: highestGw
  };
}
